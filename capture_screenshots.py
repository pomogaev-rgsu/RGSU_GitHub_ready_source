"""Capture the actual HTML responses rendered by the application in Chromium.
Chromium in this execution environment blocks navigation to localhost, therefore
server responses are fetched with requests and then rendered with inline local CSS.
No screen contents are artificially designed or drawn as images.
"""
from pathlib import Path
import re
import requests
from playwright.sync_api import sync_playwright

ROOT=Path(__file__).resolve().parent
BASE='http://127.0.0.1:8765'
STYLE=(ROOT/'static/style.css').read_text().replace("@import url('');",'')
SCRIPT='(function(){\n'+(ROOT/'static/main.js').read_text()+'\n})();'

def start_session(email):
    s=requests.Session()
    r=s.get(BASE+'/login');r.raise_for_status()
    csrf=re.search(r'name="csrf_token" value="([^"]+)',r.text).group(1)
    r=s.post(BASE+'/login',data={'email':email,'password':'Demo2026!','csrf_token':csrf})
    r.raise_for_status();assert 'Выйти из аккаунта' in r.text
    return s

def html_for(s,url):
    r=s.get(BASE+url);r.raise_for_status()
    text=r.text
    text=text.replace('<link rel="stylesheet" href="/static/style.css">',f'<style>{STYLE}</style>')
    text=text.replace('<script src="/static/main.js"></script>',f'<script>{SCRIPT}</script>')
    return text

p=ROOT/'screenshots';p.mkdir(exist_ok=True)
with sync_playwright() as engine:
    browser=engine.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--no-proxy-server'])
    tab=browser.new_page(viewport={'width':1440,'height':940},device_scale_factor=1.5,locale='ru-RU')
    tab.emulate_media(reduced_motion='reduce')
    anon=requests.Session()
    student=start_session('student@demo.local')
    employee=start_session('employee@demo.local')
    admin=start_session('admin@demo.local')
    captures=[
      ('01_login.png',anon,'/login'),
      ('02_student_dashboard.png',student,'/dashboard'),
      ('03_new_request.png',student,'/applications/new'),
      ('04_student_requests.png',student,'/applications'),
      ('05_student_request_details.png',student,'/applications/1'),
      ('06_employee_dashboard.png',employee,'/dashboard'),
      ('07_employee_request_processing.png',employee,'/applications/2'),
      ('08_administration.png',admin,'/admin'),
      ('09_notifications.png',student,'/notifications'),
      ('10_employee_all_requests.png',employee,'/applications'),
    ]
    for filename,session,path in captures:
        tab.set_content(html_for(session,path),wait_until='load')
        tab.wait_for_timeout(160)
        tab.screenshot(path=str(p/filename),full_page=True,animations='disabled')
        print(filename,tab.title(),tab.locator('body').inner_text()[:65].replace('\n',' / '))
    tab.set_content(html_for(student,'/applications/new'),wait_until='load')
    tab.locator('select[name="document_type"]').select_option('order')
    tab.wait_for_timeout(250)
    print('order selector style',tab.locator('#orderPick').get_attribute('style'))
    assert tab.locator('#orderPick').is_visible()
    tab.screenshot(path=str(p/'12_order_selection.png'),full_page=True)
    print('12_order_selection.png','browser interactive order selector OK')
    # PDF generated by the running application from a test request
    r=student.get(BASE+'/applications/1/pdf');r.raise_for_status()
    (ROOT/'outputs/sample_certificate.pdf').write_bytes(r.content)
    print('PDF from server',len(r.content),'bytes')
    browser.close()
